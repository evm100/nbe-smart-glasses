"""What a node needs to be flashed: certificates + the sdkconfig values that point it at the broker.

The server hands this out as JSON (GET /api/nodes/<ID>/credentials, used by
firmware/tools/nbe_node.py) or as a zip (node admin page). Both produce the same
files inside the ESP-IDF project:

    main/certs/client.crt     node certificate (CN = node ID), signed by the NBE Device CA
    main/certs/client.key     its private key  (never commit; .gitignore'd)
    main/certs/broker_ca.crt  only when the broker cert is NOT publicly trusted
    sdkconfig.nbe             CONFIG_PPG_* values, applied on top of sdkconfig.defaults

Wi-Fi credentials are site-specific and never stored on the server; the tool
adds them locally.
"""
from __future__ import annotations

import io
import zipfile
from pathlib import Path


def bundle(settings, registry, node_id: str) -> dict:
    creds = registry.credentials(node_id)
    prov = settings.provisioning
    ca_mode, ca_pem = "bundle", None
    if prov.get("broker_ca") not in (None, "", "bundle"):
        ca_mode, ca_pem = "pem", Path(prov["broker_ca"]).read_text()
    n = creds["node"]
    return {"node_id": n["node_id"], "name": n["name"], "site": n["site"] or "finger",
            "client_cert": creds["client_cert"], "client_key": creds["client_key"], "cert_fp": creds["cert_fp"],
            "cert_expires": n["cert_expires"], "broker_uri": prov["broker_uri"], "broker_ca_mode": ca_mode,
            "broker_ca_pem": ca_pem, "topic_prefix": prov["topic_prefix"], "ota_url": ota_url(settings)}


def ota_url(settings) -> str:
    """Where nodes download firmware updates (CONFIG_PPG_OTA_URL); empty without a public https URL."""
    u = (settings.public_url or "").rstrip("/")
    return u + "/ota" if u.startswith("https://") else ""


def sdkconfig_values(b: dict, wifi_ssid: str | None = None, wifi_password: str | None = None) -> dict[str, str | bool]:
    vals: dict[str, str | bool] = {
        "PPG_DEVICE_ID": b["node_id"], "PPG_SITE": b["site"],
        "PPG_LINK_MQTT": True, "PPG_LINK_USB_SERIAL_JTAG": False, "PPG_LINK_UART": False,
        "PPG_MQTT_BROKER_URI": b["broker_uri"], "PPG_MQTT_TOPIC_PREFIX": b["topic_prefix"],
        "PPG_MQTT_CA_BUNDLE": b["broker_ca_mode"] == "bundle", "PPG_MQTT_CA_PEM": b["broker_ca_mode"] == "pem",
        "PPG_OTA_URL": b.get("ota_url") or "",
        # USB-C no longer carries data, so put the log console there (idf.py monitor shows Wi-Fi/MQTT logs)
        "ESP_CONSOLE_USB_SERIAL_JTAG": True, "ESP_CONSOLE_UART_DEFAULT": False,
    }
    if wifi_ssid is not None:
        vals["PPG_WIFI_SSID"] = wifi_ssid
        vals["PPG_WIFI_PASSWORD"] = wifi_password or ""
    return vals


def sdkconfig_text(vals: dict) -> str:
    out = ["# Generated by nbe-node / the NBE server for this node. Applied after sdkconfig.defaults.",
           "# Do not commit (contains the node ID; Wi-Fi password if given)."]
    for k, v in vals.items():
        if v is True:
            out.append(f"CONFIG_{k}=y")
        elif v is False:
            out.append(f"# CONFIG_{k} is not set")
        else:
            esc = str(v).replace("\\", "\\\\").replace('"', '\\"')
            out.append(f'CONFIG_{k}="{esc}"')
    return "\n".join(out) + "\n"


def bundle_zip(b: dict) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("main/certs/client.crt", b["client_cert"])
        z.writestr("main/certs/client.key", b["client_key"])
        if b["broker_ca_pem"]:
            z.writestr("main/certs/broker_ca.crt", b["broker_ca_pem"])
        z.writestr("sdkconfig.nbe", sdkconfig_text(sdkconfig_values(b)))
        z.writestr("README.txt",
                   f"Credentials for node {b['node_id']}.\n\nUnzip into firmware/esp-idf/ppg_stream/ (keeps the "
                   "folder structure), add Wi-Fi with\n  idf.py menuconfig  ->  PPG stream -> Link -> Wi-Fi\n"
                   "then: rm -f sdkconfig && idf.py build flash\n\nEasier: firmware/tools/nbe_node.py configure "
                   f"{b['node_id']} (does all of this).\nThe key in main/certs/client.key identifies this board: "
                   "don't share or commit it.\n")
    return buf.getvalue()
